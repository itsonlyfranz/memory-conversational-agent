"""Regenerate the README's agent-flow diagram from the compiled LangGraph turn graph.

    python scripts/render_graph.py           # rewrite the diagram in README.md
    python scripts/render_graph.py --check   # exit 1 if README.md is out of date
    python scripts/render_graph.py --print   # print the Mermaid source only

Fully offline: the graph is compiled with the fake LLM, so no API key is needed.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from memory_agent import (
    HashingEmbedder,
    InMemoryStore,
    LongTermMemory,
    MemoryAgent,
    RelevanceScorer,
)
from memory_agent.fakes import HeuristicLLM

README = Path(__file__).resolve().parent.parent / "README.md"
BEGIN = "<!-- flow-diagram:begin (generated by scripts/render_graph.py) -->"
END = "<!-- flow-diagram:end -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)


def render_flow_mermaid() -> str:
    """Mermaid source of the real compiled turn graph."""
    memory = LongTermMemory(InMemoryStore(), HashingEmbedder(), RelevanceScorer())
    graph = MemoryAgent(HeuristicLLM(), memory).graph
    return graph.get_graph().draw_mermaid().strip()


def flow_block() -> str:
    return f"{BEGIN}\n```mermaid\n{render_flow_mermaid()}\n```\n{END}"


def update_readme(text: str) -> str:
    if not BLOCK.search(text):
        raise ValueError(f"README.md has no {BEGIN!r} ... {END!r} block")
    return BLOCK.sub(lambda _: flow_block(), text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if README.md is stale")
    mode.add_argument("--print", action="store_true", help="print the Mermaid source")
    args = parser.parse_args(argv)

    if args.print:
        print(render_flow_mermaid())
        return 0
    current = README.read_text(encoding="utf-8")
    updated = update_readme(current)
    if args.check:
        if updated != current:
            print("README.md flow diagram is stale; run scripts/render_graph.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
