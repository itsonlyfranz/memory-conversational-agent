"""Regenerate the README's agent-flow diagram from the compiled LangGraph turn graph.

    python scripts/render_graph.py   # rewrite the diagram in README.md

Fully offline: the graph is compiled with the fake LLM, so no API key is needed.
"""

from __future__ import annotations

import re
from pathlib import Path

from memory_agent import (
    HashingEmbedder,
    InMemoryStore,
    LongTermMemory,
    MemoryAgent,
    RelevanceScorer,
)
from memory_agent.fakes import HeuristicLLM

README = Path(__file__).resolve().parent.parent / "README.md"
BEGIN = "<!-- flow-diagram:begin (generated by scripts/render_graph.py) -->"
END = "<!-- flow-diagram:end -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)


def render_flow_mermaid() -> str:
    """Mermaid source of the real compiled turn graph."""
    memory = LongTermMemory(InMemoryStore(), HashingEmbedder(), RelevanceScorer())
    graph = MemoryAgent(HeuristicLLM(), memory).graph
    return graph.get_graph().draw_mermaid().strip()


def flow_block() -> str:
    return f"{BEGIN}\n```mermaid\n{render_flow_mermaid()}\n```\n{END}"


def update_readme(text: str) -> str:
    if not BLOCK.search(text):
        raise ValueError(f"README.md has no {BEGIN!r} ... {END!r} block")
    return BLOCK.sub(lambda _: flow_block(), text)


def main() -> int:
    README.write_text(update_readme(README.read_text(encoding="utf-8")), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
